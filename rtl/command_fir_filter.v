module command_fir_filter(
    input wire clk,
    input wire reset,
    input wire is_first_packet_in_array,
    input wire fir_filter_start,
    input wire awaiting_payload_fir_filter,
    input wire [15:0] payload_length,
    input wire [7:0] data_from_fifo,

    output reg [7:0] transmit_cmd,
    output wire read_next_fifo_pulse,
    output wire [7:0] data_out
);

localparam CMD_DATA = 8'hFF;
localparam FIR_TAPS = 41;
localparam HISTORY_DEPTH = 64;
localparam HISTORY_SAMPLES = FIR_TAPS - 1;
localparam TAP_INDEX_WIDTH = $clog2(FIR_TAPS);
localparam HISTORY_COUNT_WIDTH = $clog2(FIR_TAPS);

localparam STATE_WAIT       = 3'd0;
localparam STATE_READ_LOW   = 3'd1;
localparam STATE_READ_HIGH  = 3'd2;
localparam STATE_HISTORY    = 3'd3;
localparam STATE_MAC        = 3'd4;

reg [2:0] state;
reg [7:0] sample_low_byte;
reg signed [15:0] input_sample;
reg [15:0] payload_length_latch;
reg [15:0] input_bytes_loaded;
reg [TAP_INDEX_WIDTH-1:0] tap_index;
reg signed [37:0] accumulator;

// A power-of-two circular buffer stores the preceding 40 signed samples.
// It is read synchronously, one tap per MAC iteration, to keep the delay
// storage compact instead of building 640 flip-flops.
// Explicitly select block RAM rather than allowing small-memory heuristics to
// implement the 64x16 history as flip-flops.
(* ram_style = "block" *) reg signed [15:0] sample_history [0:HISTORY_DEPTH-1];
reg [HISTORY_COUNT_WIDTH-1:0] history_write_ptr;
reg [HISTORY_COUNT_WIDTH-1:0] history_count;
reg signed [15:0] history_read_data;
reg history_read_valid;
wire [HISTORY_COUNT_WIDTH-1:0] history_read_address =
    history_write_ptr - tap_index;

reg signed [15:0] current_filtered_sample;
reg signed [15:0] next_filtered_sample;
reg current_sample_valid;
reg next_sample_valid;
reg output_high_byte;

// Signed Q1.15 coefficients generated by python/fir_design.py. The symmetric
// 41-tap table has unity DC gain; each coefficient is selected over time.
function signed [15:0] coefficient_for_tap;
    input [TAP_INDEX_WIDTH-1:0] index;
    begin
        case (index)
            6'd0:  coefficient_for_tap = -16'sd150;
            6'd1:  coefficient_for_tap = -16'sd202;
            6'd2:  coefficient_for_tap = -16'sd248;
            6'd3:  coefficient_for_tap = -16'sd282;
            6'd4:  coefficient_for_tap = -16'sd296;
            6'd5:  coefficient_for_tap = -16'sd281;
            6'd6:  coefficient_for_tap = -16'sd231;
            6'd7:  coefficient_for_tap = -16'sd138;
            6'd8:  coefficient_for_tap = 16'sd0;
            6'd9:  coefficient_for_tap = 16'sd184;
            6'd10: coefficient_for_tap = 16'sd412;
            6'd11: coefficient_for_tap = 16'sd677;
            6'd12: coefficient_for_tap = 16'sd972;
            6'd13: coefficient_for_tap = 16'sd1283;
            6'd14: coefficient_for_tap = 16'sd1597;
            6'd15: coefficient_for_tap = 16'sd1898;
            6'd16: coefficient_for_tap = 16'sd2171;
            6'd17: coefficient_for_tap = 16'sd2401;
            6'd18: coefficient_for_tap = 16'sd2575;
            6'd19: coefficient_for_tap = 16'sd2684;
            6'd20: coefficient_for_tap = 16'sd2716;
            6'd21: coefficient_for_tap = 16'sd2684;
            6'd22: coefficient_for_tap = 16'sd2575;
            6'd23: coefficient_for_tap = 16'sd2401;
            6'd24: coefficient_for_tap = 16'sd2171;
            6'd25: coefficient_for_tap = 16'sd1898;
            6'd26: coefficient_for_tap = 16'sd1597;
            6'd27: coefficient_for_tap = 16'sd1283;
            6'd28: coefficient_for_tap = 16'sd972;
            6'd29: coefficient_for_tap = 16'sd677;
            6'd30: coefficient_for_tap = 16'sd412;
            6'd31: coefficient_for_tap = 16'sd184;
            6'd32: coefficient_for_tap = 16'sd0;
            6'd33: coefficient_for_tap = -16'sd138;
            6'd34: coefficient_for_tap = -16'sd231;
            6'd35: coefficient_for_tap = -16'sd281;
            6'd36: coefficient_for_tap = -16'sd296;
            6'd37: coefficient_for_tap = -16'sd282;
            6'd38: coefficient_for_tap = -16'sd248;
            6'd39: coefficient_for_tap = -16'sd202;
            6'd40: coefficient_for_tap = -16'sd150;
            default: coefficient_for_tap = 16'sd0;
        endcase
    end
endfunction

wire signed [15:0] mac_sample = (tap_index == 0) ? input_sample :
                                (history_read_valid ? history_read_data : 16'sd0);
wire signed [15:0] coefficient = coefficient_for_tap(tap_index);
wire signed [31:0] mac_product = mac_sample * coefficient;
wire signed [37:0] product_extended = {{6{mac_product[31]}}, mac_product};
wire signed [37:0] accumulated_value = accumulator + product_extended;
wire signed [37:0] scaled_result = accumulated_value >>> 15;
wire signed [15:0] filtered_sample =
    (scaled_result > 38'sd32767) ? 16'sd32767 :
    (scaled_result < -38'sd32768) ? -16'sd32768 :
    scaled_result[15:0];

assign read_next_fifo_pulse = (state == STATE_READ_LOW) ||
                              (state == STATE_READ_HIGH);

assign data_out = current_sample_valid ?
                  (output_high_byte ? current_filtered_sample[15:8] :
                                      current_filtered_sample[7:0]) :
                  8'd0;

// Keep the RAM read and write ports simple and synchronous for iCE40 EBR
// inference. Startup zero padding is selected separately from the RAM data.
always @(posedge clk) begin
    if (state == STATE_HISTORY && !reset)
        history_read_data <= sample_history[history_read_address];

    if (!reset && !fir_filter_start && state == STATE_MAC &&
        tap_index == FIR_TAPS-1)
        sample_history[history_write_ptr] <= input_sample;
end

always @(posedge clk) begin
    if (reset)
        history_read_valid <= 1'b0;
    else if (state == STATE_HISTORY)
        history_read_valid <= tap_index <= history_count;
end

always @(posedge clk) begin
    if (reset) begin
        state <= STATE_WAIT;
        sample_low_byte <= 8'd0;
        input_sample <= 16'sd0;
        payload_length_latch <= 16'd0;
        input_bytes_loaded <= 16'd0;
        tap_index <= {TAP_INDEX_WIDTH{1'b0}};
        accumulator <= 38'sd0;
        history_write_ptr <= {HISTORY_COUNT_WIDTH{1'b0}};
        history_count <= {HISTORY_COUNT_WIDTH{1'b0}};
        current_filtered_sample <= 16'sd0;
        next_filtered_sample <= 16'sd0;
        current_sample_valid <= 1'b0;
        next_sample_valid <= 1'b0;
        output_high_byte <= 1'b0;
        transmit_cmd <= 8'd0;
    end else if (fir_filter_start) begin
        transmit_cmd <= CMD_DATA;
        state <= (payload_length >= 16'd2) ? STATE_READ_LOW : STATE_WAIT;
        payload_length_latch <= payload_length;
        input_bytes_loaded <= 16'd0;
        current_sample_valid <= 1'b0;
        next_sample_valid <= 1'b0;
        output_high_byte <= 1'b0;

        // A new array starts with zero history. Continuation packets retain
        // the circular buffer and pointer from the preceding packet.
        if (is_first_packet_in_array) begin
            history_write_ptr <= {HISTORY_COUNT_WIDTH{1'b0}};
            history_count <= {HISTORY_COUNT_WIDTH{1'b0}};
        end
    end else begin
        transmit_cmd <= 8'd0;

        case (state)
            STATE_READ_LOW: begin
                sample_low_byte <= data_from_fifo;
                state <= STATE_READ_HIGH;
            end

            STATE_READ_HIGH: begin
                input_sample <= {data_from_fifo, sample_low_byte};
                tap_index <= {TAP_INDEX_WIDTH{1'b0}};
                accumulator <= 38'sd0;
                state <= STATE_MAC;
            end

            STATE_HISTORY: begin
                // The synchronous RAM read is captured by the block above;
                // use its result in the MAC state on the following clock.
                state <= STATE_MAC;
            end

            STATE_MAC: begin
                if (tap_index == FIR_TAPS-1) begin
                    accumulator <= 38'sd0;
                    input_bytes_loaded <= input_bytes_loaded + 16'd2;
                    history_write_ptr <= history_write_ptr + 1'b1;
                    if (history_count < HISTORY_SAMPLES)
                        history_count <= history_count + 1'b1;

                    if (!current_sample_valid) begin
                        current_filtered_sample <= filtered_sample;
                        current_sample_valid <= 1'b1;
                        if (input_bytes_loaded + 16'd4 <= payload_length_latch)
                            state <= STATE_READ_LOW;
                        else
                            state <= STATE_WAIT;
                    end else begin
                        next_filtered_sample <= filtered_sample;
                        next_sample_valid <= 1'b1;
                        state <= STATE_WAIT;
                    end
                end else begin
                    accumulator <= accumulated_value;
                    tap_index <= tap_index + 1'b1;
                    state <= STATE_HISTORY;
                end
            end

            default: state <= STATE_WAIT;
        endcase

        if (awaiting_payload_fir_filter && current_sample_valid) begin
            if (!output_high_byte) begin
                output_high_byte <= 1'b1;
            end else begin
                output_high_byte <= 1'b0;
                if (next_sample_valid) begin
                    current_filtered_sample <= next_filtered_sample;
                    next_sample_valid <= 1'b0;
                    if (input_bytes_loaded + 16'd2 <= payload_length_latch)
                        state <= STATE_READ_LOW;
                    else
                        state <= STATE_WAIT;
                end else begin
                    current_sample_valid <= 1'b0;
                end
            end
        end
    end
end

endmodule
